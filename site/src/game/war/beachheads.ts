/** Who holds a bunker: a colony AND the home world its troops came from.
 *  The worldId is the threat model (§5) made data — a beachhead on one
 *  world can be held by troops from several worlds at once. */
export interface ControllerRef {
  colonyId: string;
  colonyName: string;
  /** The controller's HOME world (server/world id) — where these troops
   *  jumped from, not where the beachhead sits. */
  worldId: string;
  // — presence fields (layout §4.1, Oct 15 2026) — stamped SERVER-SIDE in
  // beachheadOrderFn from the actor's real state at order time (snapshot
  // semantics: a force flies the banner it marched under; reinforcement
  // re-stamps). Display data only — `sameController` identity stays
  // (colonyId, worldId). All optional: fields stamped before this growth
  // (and the Chronicle systems that will feed hero/title/radiance) read
  // as null/0 and rendering degrades to name + holder color.
  /** The actor's war band, when they hold one. */
  allianceId?: string | null;
  allianceName?: string | null;
  /** Alliance.banner — the band's emblem key. */
  allianceBanner?: string | null;
  /** Hero leading the force, when one is committed (no beachhead force
   *  carries a hero yet — the hook waits, per layout §4.1). */
  heroId?: string | null;
  /** Earned title / Chronicle standing line (awaits the Chronicle). */
  title?: string | null;
  /** Gilt Chronicle radiance tier 0..3 (awaits the Chronicle system;
   *  0 = base presence glow — size and light are never bought). */
  radianceTier?: number;
  /** Equipped banner/standard cosmetic (paid-permanent; awaits sets). */
  standardId?: string | null;
}

/** The Chorus as a controller (its garrisons are seeded, §6). */
export function chorusController(worldId: string): ControllerRef {
  return { colonyId: "chorus", colonyName: "The Chorus", worldId };
}

export function sameController(a: ControllerRef | null, b: ControllerRef): boolean {
  return !!a && a.colonyId === b.colonyId && a.worldId === b.worldId;
}

/** One slice of a committed force: a troop type at a tier, with a count.
 *  Forces are stored as parts so power math (type × tier × weight) stays
 *  exact and relief can hand the SAME bodies back to the roster. */
export interface ForcePart {
  type: TroopType;
  tier: TroopTier;
  count: number;
}

/** Bodies committed somewhere: a bunker garrison, a conversion crew, or a
 *  defender force re-entered into a converting bunker. */
export interface CommittedForce {
  owner: ControllerRef;
  parts: ForcePart[];
  committedAt: number;
}

export function forceCounts(f: CommittedForce | null | undefined): Record<TroopType, number> {
  const out: Record<TroopType, number> = { bulwark: 0, reaver: 0, longeye: 0, thunder: 0, warden: 0 };
  for (const p of f?.parts ?? []) out[p.type] += p.count;
  return out;
}

export function forceCount(f: CommittedForce | null | undefined): number {
  return (f?.parts ?? []).reduce((n, p) => n + p.count, 0);
}

export function forceWeight(f: CommittedForce | null | undefined): number {
  return (f?.parts ?? []).reduce((n, p) => n + p.count * supplyWeight(p.type), 0);
}

/** Battle power of a committed force — rosterPower's formula exactly
 *  (Σ count × supply weight × tier power), so a bunker force prices the
 *  same at the beachhead as it did in the muster yard. */
export function forcePower(f: CommittedForce | null | undefined): number {
  return (f?.parts ?? []).reduce((n, p) => n + p.count * supplyWeight(p.type) * tierPowerMult(p.tier), 0);
}

/** §4A conversion state: the taker's crew is doing the work (clear, haul,
 *  restock) while the clock runs. `progressMs` accumulates ONLY while no
 *  defender force is inside (SEAM Q3: re-entry pauses, provisional). */
export interface ConversionState {
  /** The taker — becomes the controller when the bunker goes solid. */
  by: ControllerRef;
  /** The beaten controller — may re-enter and restock until solid (§4A). */
  defender: ControllerRef;
  startedAt: number;
  /** Accumulated conversion work (ms). Pauses while defenderForce is in. */
  progressMs: number;
  /** Duration required — stamped from config at start (provisional §4A). */
  durationMs: number;
  /** The taker's surviving force, doing the conversion work. Becomes the
   *  garrison when the bunker goes solid. */
  crew: CommittedForce;
  /** Defender bodies back inside (§4A re-entry). Their presence pauses
   *  the clock; if the taker clears them out (assault), the clock resumes. */
  defenderForce: CommittedForce | null;
}

export interface Bunker {
  id: string; // `bk-<beachheadId>-<n>`
  sectorId: string;
  /** Position on the front, normalized: x along the shore 0..1 (the whole
   *  beachhead, any size), y depth 0 (shore) .. 1 (rear). The wide view
   *  pans over x; sectors are x-bands. Same normalized-coordinate contract
   *  the battle radar selection model uses. */
  x: number;
  y: number;
  depth: BeachheadDepth;
  /** Whose ground this is. Null = never claimed. A controller with no
   *  garrison and no conversion is a CLAIM WITHOUT BODIES — still an open
   *  door (§2): anyone who moves in takes it, no conversion needed, since
   *  nobody was beaten here. */
  controller: ControllerRef | null;
  /** The dedicated garrison (§4). Null = the position stands empty. */
  garrison: CommittedForce | null;
  /** §4A: a takeover being converted. Mutually exclusive with `garrison`
   *  EXCEPT the defender's re-entered force lives inside the conversion. */
  conversion: ConversionState | null;
}

export interface BeachheadSector {
  id: string; // `sec-<beachheadId>-<n>`
  index: number;
  label: string;
  bunkerIds: string[];
}

export interface Beachhead {
  id: string; // `bh-<seq>`
  /** Display name (beachhead-names.ts owns the naming honors; phase 1
   *  seeds the generic phonetic form). */
  name: string;
  /** The world this front sits ON — the defending world. Attackers carry
   *  their own home worldId in their ControllerRef (§5). */
  worldId: string;
  /** The designed layout (§3) — data: sectors of fixed positions. */
  sectors: BeachheadSector[];
  bunkers: Bunker[];
  createdAt: number;
  /** Monotonic stamp for the advance loop's per-bunker tick bookkeeping. */
  lastAdvanceAt: number;
}

/** The at-a-glance control state the wide view renders (§1 / §8 Q11 —
 *  the four ruled states plus the claim-without-bodies reading). */
export type BunkerViewState = "empty" | "held" | "converting" | "contested";

export function bunkerViewState(b: Bunker): BunkerViewState {
  if (b.conversion) return b.conversion.defenderForce ? "contested" : "converting";
  if (b.garrison) return "held";
  return "empty";
}

/** Conversion progress 0..1 for the wide view's progress ring (§4A).
 *  Stored progress is booked at the beachhead's last advance tick; this
 *  reads it live (frozen while defender bodies are inside — SEAM Q3). */
export function conversionProgress(bh: Beachhead, b: Bunker, now: number): number {
  const c = b.conversion;
  if (!c) return 0;
  const live = c.defenderForce ? c.progressMs : c.progressMs + Math.max(0, now - bh.lastAdvanceAt);
  return Math.min(1, live / c.durationMs);
}

// ============================================================================
// §2 LAYOUT — designed positions by formula (§3). Deterministic: a seeded
// hash, never Math.random, so every client and the server agree on the map.
// 1,000 bunkers is a count change, not a rewrite.
// ============================================================================

/** Small deterministic hash → [0,1). FNV-1a over the key string. */
function hash01(key: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < key.length; i++) {
    h ^= key.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return ((h >>> 0) % 10000) / 10000;
}

/**
 * Generate a beachhead layout: `totalBunkers` fixed positions in sectors
 * of BEACHHEAD_CONFIG.sectorSize along a shore, each sector spread over
 * the depth rows by depthShare. Positions are normalized (x 0..1 across
 * the whole front, y by depth row with deterministic jitter).
 * SEAM (Q9): the row structure is the phase-1 default geometry — Hans's
 * layout ruling replaces the generator's shape, not its contract.
 */
export function generateBeachheadLayout(
  beachheadId: string,
  totalBunkers: number,
): { sectors: BeachheadSector[]; bunkers: Bunker[] } {
  const { sectorSize, depthRows, depthShare } = BEACHHEAD_CONFIG;
  const total = Math.max(1, Math.trunc(totalBunkers));
  const sectorCount = Math.ceil(total / sectorSize);
  const sectors: BeachheadSector[] = [];
  const bunkers: Bunker[] = [];
  let n = 0;
  for (let s = 0; s < sectorCount; s++) {
    const sector: BeachheadSector = {
      id: `sec-${beachheadId}-${s}`,
      index: s,
      label: `Sector ${s + 1}`,
      bunkerIds: [],
    };
    const inSector = Math.min(sectorSize, total - s * sectorSize);
    for (let i = 0; i < inSector; i++, n++) {
      // Depth assignment by share, interleaved so every stretch of shore
      // has its depth behind it: cumulative-share walk over the sector.
      const frac = (i + 0.5) / inSector;
      let row = depthRows.length - 1;
      let acc = 0;
      for (let r = 0; r < depthRows.length; r++) {
        acc += depthShare[r];
        if (frac <= acc) { row = r; break; }
      }
      const depth = depthRows[row];
      // x: even spread within the sector's band + deterministic jitter.
      const bandX = (s + (i + 0.5) / inSector) / sectorCount;
      const jitter = (hash01(`${beachheadId}:${n}:x`) - 0.5) * (0.6 / total);
      const x = Math.min(0.999, Math.max(0.001, bandX + jitter));
      // y: the depth row's band + jitter (shore 0 → rear 1).
      const yBase = row / (depthRows.length - 1);
      const y = Math.min(0.99, Math.max(0.01, yBase + (hash01(`${beachheadId}:${n}:y`) - 0.5) * 0.18));
      const bunker: Bunker = {
        id: `bk-${beachheadId}-${n}`,
        sectorId: sector.id,
        x,
        y,
        depth,
        controller: null,
        garrison: null,
        conversion: null,
      };
      sector.bunkerIds.push(bunker.id);
      bunkers.push(bunker);
    }
    sectors.push(sector);
  }
  return { sectors, bunkers };
}

/**
 * Seed the playable first strip (§3 + §6): a fresh beachhead whose shore
 * the Chorus holds in pickets + an eastern strongpoint, G3 Bulwark flavor,
 * everything else standing empty — open doors for the landing force.
 */
export function seedFirstStripBeachhead(args: {
  id: string;
  name: string;
  worldId: string;
  now: number;
  totalBunkers?: number;
}): Beachhead {
  const total = args.totalBunkers ?? BEACHHEAD_CONFIG.firstStripBunkers;
  const { sectors, bunkers } = generateBeachheadLayout(args.id, total);
  const chorus = chorusController(args.worldId);
  const cfg = BEACHHEAD_CONFIG;
  bunkers.forEach((b, i) => {
    const picket = i % cfg.seedChorusEveryNth === cfg.seedChorusEveryNth - 1;
    const strongpoint = i >= cfg.seedStrongpointStart && i <= cfg.seedStrongpointEnd;
    if (!picket && !strongpoint) return;
    const parts: ForcePart[] = Object.entries(cfg.seedChorusGarrison)
      .filter(([, count]) => (count ?? 0) > 0)
      .map(([type, count]) => ({ type: type as TroopType, tier: 1 as TroopTier, count: count ?? 0 }));
    b.controller = chorus;
    b.garrison = { owner: chorus, parts, committedAt: args.now };
  });
  return {
    id: args.id,
    name: args.name,
    worldId: args.worldId,
    sectors,
    bunkers,
    createdAt: args.now,
    lastAdvanceAt: args.now,
  };
}

// ============================================================================
// §3 FORCE DRAWING — real bodies out of a real roster (the dedication, §4).
// Drawing is newest-first per type (the roster's own death order), tier-
// exact: the parts record WHICH bodies went, so relief returns the same.
// ============================================================================

export type TroopCounts = Partial<Record<TroopType, number>>;

function cleanCounts(counts: TroopCounts): Record<TroopType, number> {
  const out: Record<TroopType, number> = { bulwark: 0, reaver: 0, longeye: 0, thunder: 0, warden: 0 };
  for (const t of TROOP_TYPES) out[t] = Math.max(0, Math.trunc(counts[t] ?? 0));
  return out;
}

function countsWeight(counts: Record<TroopType, number>): number {
  return TROOP_TYPES.reduce((n, t) => n + counts[t] * supplyWeight(t), 0);
}

/**
 * Draw a force of the requested composition out of a roster. Validates
 * against the roster's REAL availability — per-type headcount and the
 * uncommitted weight ledger (troops committed to a battle cannot be
 * double-spent into a garrison). Mutates the roster on success only.
 */
export function drawForce(
  roster: TroopRoster,
  countsIn: TroopCounts,
  owner: ControllerRef,
  now: number,
): { ok: true; force: CommittedForce } | { ok: false; error: string } {
  const counts = cleanCounts(countsIn);
  const total = TROOP_TYPES.reduce((n, t) => n + counts[t], 0);
  if (total <= 0) return { ok: false, error: "Pick at least one troop." };
  const have = rosterByType(roster);
  for (const t of TROOP_TYPES) {
    if (counts[t] > have[t]) {
      return { ok: false, error: `Only ${have[t]} ${t} in the garrison — can't send ${counts[t]}.` };
    }
  }
  if (countsWeight(counts) > availableWeight(roster)) {
    return { ok: false, error: "Some of those troops are committed to a battle — they can't be double-spent." };
  }
  // Take newest-first per type, recording (type, tier) parts exactly.
  const parts: ForcePart[] = [];
  for (const t of TROOP_TYPES) {
    let left = counts[t];
    if (left <= 0) continue;
    const cohorts = roster.cohorts
      .filter((c) => c.type === t && c.count > 0)
      .sort((a, b) => b.musteredAt - a.musteredAt || b.id.localeCompare(a.id));
    for (const c of cohorts) {
      if (left <= 0) break;
      const take = Math.min(c.count, left);
      c.count -= take;
      c.veterans = Math.max(0, c.veterans - Math.min(c.veterans, take));
      left -= take;
      const tier = (c.tier ?? 1) as TroopTier;
      const existing = parts.find((p) => p.type === t && p.tier === tier);
      if (existing) existing.count += take;
      else parts.push({ type: t, tier, count: take });
    }
  }
  roster.cohorts = roster.cohorts.filter((c) => c.count > 0);
  parts.sort((a, b) => a.type.localeCompare(b.type) || a.tier - b.tier);
  return { ok: true, force: { owner, parts, committedAt: now } };
}

/** Hand a force's bodies back to a roster (relief, a beaten assault's
 *  survivors coming home). The same (type, tier) bodies return. */
export function returnForce(roster: TroopRoster, force: CommittedForce, now: number): void {
  for (const p of force.parts) {
    if (p.count > 0) addCohort(roster, p.type, p.count, now, 0, p.tier);
  }
}

/** Merge additional drawn troops into an existing committed force. */
function mergeInto(force: CommittedForce, drawn: CommittedForce): void {
  for (const p of drawn.parts) {
    const existing = force.parts.find((q) => q.type === p.type && q.tier === p.tier);
    if (existing) existing.count += p.count;
    else force.parts.push({ ...p });
  }
  force.parts.sort((a, b) => a.type.localeCompare(b.type) || a.tier - b.tier);
}

/**
 * Apply a casualty fraction to a force's parts, deterministically:
 * per-part round(count × frac), at least the fraction's round of the
 * whole. Returns the surviving force (parts pruned of zeros).
 */
function tollForce(force: CommittedForce, frac: number): CommittedForce {
  const f = Math.min(1, Math.max(0, frac));
  const parts = force.parts
    .map((p) => ({ ...p, count: p.count - Math.round(p.count * f) }))
    .filter((p) => p.count > 0);
  return { ...force, parts };
}

/** BATTLES_CONFIG's published casualty curve, mirrored for the assault
 *  seam: winner pays win-frac (falls with the gap), loser pays lose-frac
 *  (rises with it), a standoff bleeds both at the standoff fraction. */
function casualtyFracs(attackerPower: number, defenderPower: number): { winFrac: number; loseFrac: number } {
  const c = BATTLES_CONFIG;
  const max = Math.max(attackerPower, defenderPower);
  const gap = max > 0 ? Math.abs(attackerPower - defenderPower) / max : 0;
  if (attackerPower === defenderPower) return { winFrac: c.casualtyStandoff, loseFrac: c.casualtyStandoff };
  return {
    winFrac: Math.min(c.casualtyMaxFrac, c.casualtyWinBase - c.casualtyWinGapDrop * gap),
    loseFrac: Math.min(c.casualtyMaxFrac, c.casualtyLoseBase + c.casualtyLoseGapRise * gap),
  };
}

// ============================================================================
// §4 THE VERBS — judge paths. Every verb validates against the beachhead's
// own state and the caller's real roster; nothing here fabricates troops.
