// Oct 13 2026). The ground an invasion holds on someone else's world: a
// miles-long front of BUNKERS in sectors, held by DEDICATED garrisons —
// presence = control, absence = an open door.
//
// WHAT IS RULED AND BUILT HERE (§ references are beachhead.md):
//   • THE WIDE PICTURE (§1): the layout model + state the wide screen pans
//     over; equal access — nothing in this module gates the view by rank.
//   • BUNKERS (§2): fixed positions from a designed layout (data, not
//     scatter). Troops placed in a bunker HOLD. An EMPTY bunker (no bodies,
//     no conversion running) is occupied by whoever moves troops in —
//     instantly, no ritual: presence = control.
//   • SCALE (§3): the layout is generated by formula into sectors, so the
//     ≈1,000-bunker design target is a DATA problem (raise the count), not
//     a rewrite. The playable first strip is 50 ("half an alliance").
//   • DEDICATED GARRISON (§4): garrisoning physically draws real troops out
//     of the home roster (newest-first, by the roster's own weight ledger).
//     They are gone from home until RELIEVED — relief (a fresh force takes
//     the bunker, the old one returns home) is the release path doctrine
//     already blesses. Free recall is NOT built: §8 Q7 is unruled (seam).
//   • CAPTURE = CONVERSION (§4A — RULED, duration provisional): beating a
//     garrison does not make the bunker yours. The winner's survivors stay
//     as a conversion CREW and a timer runs (~30 min PROVISIONAL — config,
//     tune-in-play, never hard-locked) while they clear the dead, haul out
//     enemy shells and stock their own. Until it goes SOLID the defender
//     may re-enter and restock; while defender bodies are back inside, the
//     timer PAUSES. SEAM (§8 Q3): pause-vs-reset on re-entry is UNRULED —
//     this module PAUSES (progress kept, clock frozen) as the provisional
//     seam behavior; flipping to reset is a one-line change when Hans rules.
//   • THREAT MODEL (§5): a bunker controller is a (colony, HOME WORLD)
//     pair. Nothing here assumes one attacking world — three planets'
//     troops can hold bunkers on the same beachhead simultaneously.
//   • CONVERSION TICKS on the engine advance (advanceBeachhead, called from
//     engine.advance alongside advanceBattles) — the front keeps working
//     while the commander is elsewhere (the multitask doctrine).
//
// WHAT IS DELIBERATELY NOT HERE (marked seams, §8 — do not invent):
//   • Q1 bunker capacity limits (garrisons are uncapped in phase 1).
//   • Q2 player-built/upgraded positions (layout is fixed data).
//   • Q4 HOLD fire behavior, Q5 siege-vs-bunker, Q6 bunkers-vs-breach —
//     combat BETWEEN garrisons resolves through the assault verb's
//     deterministic strength comparison, a SEAM toward real Battle
//     entities (war/battle-engine.ts); the beachhead never re-implements
//     the battle engine.
//   • Q7 free recall / rotation (only relief releases a garrison).
//   • Q9 layout geometry — the generator's shore/mid/rear rows are the
//     phase-1 default DATA, awaiting Hans's geometry ruling.
//   • Q10 a cap on simultaneous fronts; Q12 beachhead↔FOB win/loss
//     relationship; Q13 attacker-side dug-in positions beyond garrisoning
