export interface BeachheadOrderResult {
  ok: boolean;
  error?: string;
  /** What happened, in the war layer's voice — the caller logs it. */
  note?: string;
}

function findBunker(bh: Beachhead, bunkerId: string): Bunker | undefined {
  return bh.bunkers.find((b) => b.id === bunkerId);
}

/**
 * GARRISON — move troops into a position (§2/§4). The one verb, four
 * ruled cases:
 *   • Empty position (no garrison, no conversion): the mover OWNS it the
 *     moment bodies arrive — presence = control, even over a stale claim.
 *   • Converting, actor is the DEFENDER (§4A re-entry): the force moves
 *     back in as the conversion's defenderForce; the clock pauses.
 *   • Converting, defenderForce already in and actor is the defender:
 *     restocking — the force merges into defenderForce.
 *   • Converting, actor is the TAKER: the force reinforces the crew.
 * Anyone else's garrison already inside → refused (that's an assault).
 * A THIRD world walking into someone else's conversion → refused (seam:
 * multi-party conversion contests are §8 Q10 territory, unruled).
 */
export function garrisonBunker(
  bh: Beachhead,
  bunkerId: string,
  actor: ControllerRef,
  roster: TroopRoster,
  counts: TroopCounts,
  now: number,
): BeachheadOrderResult {
  const b = findBunker(bh, bunkerId);
  if (!b) return { ok: false, error: "No such bunker on this beachhead." };

  if (b.conversion) {
    const conv = b.conversion;
    if (sameController(conv.by, actor)) {
      const drawn = drawForce(roster, counts, actor, now);
      if (!drawn.ok) return drawn;
      mergeInto(conv.crew, drawn.force);
      return { ok: true, note: `Conversion crew reinforced at ${b.id}.` };
    }
    if (sameController(conv.defender, actor)) {
      const drawn = drawForce(roster, counts, actor, now);
      if (!drawn.ok) return drawn;
      if (conv.defenderForce) mergeInto(conv.defenderForce, drawn.force);
      else conv.defenderForce = drawn.force;
      return { ok: true, note: `Defenders re-entered ${b.id} — the conversion clock is paused while they hold inside.` };
    }
    return { ok: false, error: "That position is being converted — the fight for it is between its taker and its defender." };
  }

  if (b.garrison) {
    if (sameController(b.garrison.owner, actor)) {
      const drawn = drawForce(roster, counts, actor, now);
      if (!drawn.ok) return drawn;
      mergeInto(b.garrison, drawn.force);
      return { ok: true, note: `${b.id} garrison reinforced.` };
    }
    return { ok: false, error: "That bunker is held — you'll have to assault it, not walk in." };
  }

  const drawn = drawForce(roster, counts, actor, now);
  if (!drawn.ok) return drawn;
  b.garrison = drawn.force;
  b.controller = actor;
  return { ok: true, note: `${actor.colonyName} garrisoned ${b.id} — the position is held.` };
}

/**
 * ASSAULT — beat the bodies inside a position (SEAM toward real Battle
 * entities; the strength comparison is the battle engine's discipline in
 * miniature: composition-only power, published casualty curve, fully
 * deterministic). The strike force is drawn from the attacker's roster at
 * launch; survivors of a loss come home, survivors of a win stay.
 *   • vs a GARRISON: a win destroys the garrison as a force (beaten =
 *     cleared, §4A) and starts the conversion with the survivors as crew.
 *   • vs a CONVERSION's defenderForce (the taker clearing re-entry): a
 *     win destroys it and the clock resumes.
 *   • vs a CONVERSION's CREW (the defender retaking): a win cancels the
 *     conversion; the defender's survivors become the garrison and the
 *     ground is the defender's again.
 * Nobody assaults their own troops; an empty position is walked into,
 * not assaulted.
 */
export function assaultBunker(
  bh: Beachhead,
  bunkerId: string,
  actor: ControllerRef,
  roster: TroopRoster,
  counts: TroopCounts,
  now: number,
): BeachheadOrderResult {
  const b = findBunker(bh, bunkerId);
  if (!b) return { ok: false, error: "No such bunker on this beachhead." };

  // Identify the target force + what a win means here.
  let target: CommittedForce | null = null;
  let targetKind: "garrison" | "defenderForce" | "crew" | null = null;
  if (b.conversion) {
    const conv = b.conversion;
    if (conv.defenderForce && !sameController(conv.defenderForce.owner, actor)) {
      target = conv.defenderForce;
      targetKind = "defenderForce";
    } else if (!sameController(conv.crew.owner, actor) && sameController(conv.defender, actor)) {
      target = conv.crew;
      targetKind = "crew";
    } else if (!sameController(conv.crew.owner, actor)) {
      return { ok: false, error: "That conversion isn't yours to contest — its defender must retake it." };
    }
  } else if (b.garrison && !sameController(b.garrison.owner, actor)) {
    target = b.garrison;
    targetKind = "garrison";
  }
  if (!target || !targetKind) {
    if (b.garrison || b.conversion) return { ok: false, error: "Those are your own troops in there." };
    return { ok: false, error: "Nothing to assault — the position stands empty. Garrison it and it's yours." };
  }

  const drawn = drawForce(roster, counts, actor, now);
  if (!drawn.ok) return drawn;
  const strike = drawn.force;
  const atkPower = forcePower(strike);
  const defPower = forcePower(target);
  const { winFrac, loseFrac } = casualtyFracs(atkPower, defPower);
  const won = atkPower > defPower;

  if (!won) {
    // Attacker pays the loser toll and comes home; the defenders pay the
    // winner's toll where they stand.
    const survivors = tollForce(strike, loseFrac);
    returnForce(roster, survivors, now);
    const tolled = tollForce(target, winFrac);
    if (targetKind === "garrison") b.garrison = forceCount(tolled) > 0 ? tolled : null;
    else if (targetKind === "defenderForce" && b.conversion) b.conversion.defenderForce = forceCount(tolled) > 0 ? tolled : null;
    else if (targetKind === "crew" && b.conversion) b.conversion.crew = tolled;
    return {
      ok: true,
      note: `Assault on ${b.id} repelled — ${forceCount(strike) - forceCount(survivors)} attackers lost; the position holds.`,
    };
  }

  // Won: the beaten force is gone (destroyed/routed as a force — §4A's
  // clearing is the conversion crew's work now); the winners pay the
  // winner's toll and stay.
  const survivors = tollForce(strike, winFrac);
  if (targetKind === "garrison") {
    const previous = b.controller ?? target.owner;
    b.garrison = null;
    b.conversion = {
      by: actor,
      defender: previous,
      startedAt: now,
      progressMs: 0,
      durationMs: BEACHHEAD_CONFIG.conversionMs,
      crew: survivors,
      defenderForce: null,
    };
    // Control passes to the taker on the map the moment the fight is won;
    // SOLIDITY is what the timer decides (§4A) — until then the defender
    // may re-enter, and the wide view reads the bunker as converting.
    b.controller = actor;
    return {
      ok: true,
      note: `${actor.colonyName} took ${b.id} — conversion begun. It goes solid in ${Math.round(BEACHHEAD_CONFIG.conversionMs / 60000)} minutes unless the defender re-enters.`,
    };
  }
  if (targetKind === "defenderForce" && b.conversion) {
    b.conversion.defenderForce = null;
    mergeInto(b.conversion.crew, survivors);
    return { ok: true, note: `Re-entry at ${b.id} cleared — the conversion clock runs again.` };
  }
  // targetKind === "crew": the defender retook their ground mid-conversion.
  if (b.conversion) {
    b.conversion = null;
  }
  b.garrison = survivors;
  b.controller = actor;
  return { ok: true, note: `${actor.colonyName} retook ${b.id} — the conversion is undone and the position is held again.` };
}

/**
 * RELIEVE — the doctrine-blessed release (§4): a fresh force takes the
 * bunker and the old garrison's surviving bodies return home. Only the
 * garrison's owner, only a held (non-converting) bunker. Free recall
 * without relief is NOT a verb — §8 Q7 is unruled (seam).
 */
export function relieveBunker(
  bh: Beachhead,
  bunkerId: string,
  actor: ControllerRef,
  roster: TroopRoster,
  counts: TroopCounts,
  now: number,
): BeachheadOrderResult {
  const b = findBunker(bh, bunkerId);
  if (!b) return { ok: false, error: "No such bunker on this beachhead." };
  if (b.conversion) return { ok: false, error: "That position is mid-conversion — there's no garrison to relieve." };
  if (!b.garrison) return { ok: false, error: "The position stands empty — nothing to relieve." };
  if (!sameController(b.garrison.owner, actor)) return { ok: false, error: "Only the garrison's own commander can relieve it." };
  const drawn = drawForce(roster, counts, actor, now);
  if (!drawn.ok) return drawn;
  returnForce(roster, b.garrison, now);
  b.garrison = drawn.force;
  b.controller = actor;
  return { ok: true, note: `${b.id} relieved — the old garrison marched home; the fresh force holds.` };
}

// ============================================================================
// §5 ADVANCE — conversion ticking on the engine's lazy clock. Conversions
// complete whether or not anyone is watching (multitask doctrine). Returns
// event notes for the caller's log/mail. Idempotent: progress is booked
// against lastAdvanceAt, so double-ticks never double-count.
// ============================================================================

export interface BeachheadEvent {
  bunkerId: string;
  kind: "solid";
  note: string;
}

export function advanceBeachhead(bh: Beachhead, now: number): BeachheadEvent[] {
  const events: BeachheadEvent[] = [];
  const elapsed = Math.max(0, now - bh.lastAdvanceAt);
  bh.lastAdvanceAt = now;
  if (elapsed === 0) return events;
  for (const b of bh.bunkers) {
    const conv = b.conversion;
    if (!conv) continue;
    // SEAM (Q3): defender bodies inside pause the clock — provisional.
    if (conv.defenderForce) continue;
    conv.progressMs += elapsed;
    if (conv.progressMs >= conv.durationMs) {
      b.garrison = conv.crew;
      b.controller = conv.by;
      b.conversion = null;
      events.push({
        bunkerId: b.id,
        kind: "solid",
        note: `${b.id} on ${bh.name} has gone SOLID for ${conv.by.colonyName} — cleared, restocked, and held.`,
      });
    }
  }
  return events;
}

// ============================================================================
// §6 READS — the wide view's summary (§1: read the line's weak spots).
// ============================================================================

export interface BeachheadSummary {
  total: number;
  empty: number;
  heldByViewer: number;
  heldByOthers: number;
  converting: number;
  contested: number;
  /** Per-sector held/empty counts — the weak-spot read. */
  sectors: { sectorId: string; label: string; held: number; empty: number; converting: number }[];
}

export function beachheadSummary(bh: Beachhead, viewer: ControllerRef): BeachheadSummary {
  const sum: BeachheadSummary = {
    total: bh.bunkers.length,
    empty: 0,
    heldByViewer: 0,
    heldByOthers: 0,
    converting: 0,
    contested: 0,
    sectors: bh.sectors.map((s) => ({ sectorId: s.id, label: s.label, held: 0, empty: 0, converting: 0 })),
  };
  const sectorById = new Map(sum.sectors.map((s) => [s.sectorId, s]));
  for (const b of bh.bunkers) {
    const state = bunkerViewState(b);
    const sec = sectorById.get(b.sectorId);
    if (state === "empty") {
      sum.empty++;
      if (sec) sec.empty++;
    } else if (state === "converting") {
      sum.converting++;
      if (sec) sec.converting++;
    } else if (state === "contested") {
      sum.contested++;
      if (sec) sec.converting++;
    } else {
      if (sec) sec.held++;
      if (sameController(b.garrison?.owner ?? b.controller, viewer)) sum.heldByViewer++;
      else sum.heldByOthers++;
    }
  }
  return sum;
}
